import fs from 'fs/promises'
import path from 'path'
import { stringify } from 'yaml'

// The site's deploy workflow, `.github/workflows/deploy.yml` (ROADMAP-ai.md
// L6 step 5): one shared build job (`npm ci`, `npm run build`, the `public/`
// folder as an artifact) plus the deploy job of the target adapter. Only
// `nera publish` writes it, and it overwrites the file only while the file
// still starts with GENERATED_HEADER, so a workflow the user took over stays
// theirs.
//
// The fixed part is hand-written text, so its comments and layout stay
// stable; the adapter's part is data, rendered with `yaml`. Action versions
// follow nera-website's own deploy workflow.

export const WORKFLOW_FILE = path.join('.github', 'workflows', 'deploy.yml')

// The artifact the build job uploads; a deploy job downloads it by this name.
export const BUILD_ARTIFACT = 'site'
// The folder `npm run build` renders into, which the artifact holds.
export const BUILD_OUTPUT = 'public'

// The shared build job's id and the names of its steps, as the Actions API
// reports them; status.js picks its fix hint by them.
export const BUILD_JOB_ID = 'build'
export const BUILD_STEPS = {
    install: 'Install dependencies',
    render: 'Render site',
    upload: 'Upload the built site',
}

export const GENERATED_HEADER = '# Generated by `nera publish` (@nera-static/nera).'

const HEADER = `${GENERATED_HEADER}
# It builds the site and deploys it on every push to main. \`nera publish\`
# rewrites this file while its first line is unchanged; remove that line to
# keep your own edits.`

// What every workflow token needs: reading the repository. An adapter adds
// the scopes its deploy needs.
const BASE_PERMISSIONS = { contents: 'read' }
const PERMISSION_LEVELS = ['none', 'read', 'write']

const BUILD_JOB = `    ${BUILD_JOB_ID}:
        runs-on: ubuntu-latest

        steps:
            - uses: actions/checkout@v7

            - name: Use Node.js 24
              uses: actions/setup-node@v7
              with:
                  node-version: 24
                  cache: 'npm'

            - name: ${BUILD_STEPS.install}
              run: npm ci

            - name: ${BUILD_STEPS.render}
              run: npm run build

            - name: ${BUILD_STEPS.upload}
              uses: actions/upload-artifact@v7
              with:
                  name: ${BUILD_ARTIFACT}
                  path: ${BUILD_OUTPUT}
                  if-no-files-found: error`

// The adapter's deploy job, checked: `{ permissions, job }`, where
// `permissions` maps scopes to none/read/write and `job` is a job object
// without `needs` (the workflow sets `needs: build`).
async function deployJobOf(adapter, ctx) {
    const result = await adapter.deployJob(ctx)
    const where = `Publish target "${adapter.id}": deployJob()`
    if (!result || typeof result !== 'object' || !result.job || typeof result.job !== 'object' || Array.isArray(result.job)) {
        throw new TypeError(`${where} must return { permissions, job } with a job object`)
    }
    for (const key of ['needs', 'permissions']) {
        if (key in result.job) {
            throw new TypeError(`${where} must not set job.${key}; the workflow sets it`)
        }
    }
    const permissions = result.permissions ?? {}
    for (const [scope, level] of Object.entries(permissions)) {
        if (!PERMISSION_LEVELS.includes(level)) {
            throw new TypeError(`${where} permission "${scope}" must be one of ${PERMISSION_LEVELS.join(', ')}, got ${JSON.stringify(level)}`)
        }
    }
    return { permissions, job: result.job }
}

// The base permissions merged with the adapter's; the higher level wins, so
// an adapter can add a scope but never take `contents: read` away.
function mergePermissions(extra) {
    const merged = { ...BASE_PERMISSIONS }
    for (const [scope, level] of Object.entries(extra)) {
        const current = merged[scope]
        if (current === undefined || PERMISSION_LEVELS.indexOf(level) > PERMISSION_LEVELS.indexOf(current)) {
            merged[scope] = level
        }
    }
    return merged
}

// `text` indented by `spaces`, blank lines left empty.
function indent(text, spaces) {
    const pad = ' '.repeat(spaces)
    return text.split('\n').map((line) => (line === '' ? line : pad + line)).join('\n')
}

// The workflow for `adapter` as text. `ctx` is handed to adapter.deployJob.
export async function renderWorkflow(adapter, ctx = {}) {
    const { permissions, job } = await deployJobOf(adapter, ctx)
    // Only the deploy job gets the adapter's scopes: the build job runs
    // `npm ci` (dependency install scripts) with `contents: read` alone.
    const deploy = { needs: BUILD_JOB_ID, permissions: mergePermissions(permissions), ...job }
    const deployJob = stringify({ deploy }, { indent: 4, lineWidth: 0 }).trimEnd()

    return `${HEADER}

name: ${stringify(`Deploy to ${adapter.label}`).trimEnd()}

on:
    push:
        branches: [main]
    # Allow a manual run from the Actions tab.
    workflow_dispatch:

# Least-privilege token: read the repository. The deploy job adds what its
# host needs.
permissions:
    contents: read

# Never run two deploys at once; let an in-progress run finish rather than
# cancelling it mid-publish.
concurrency:
    group: deploy
    cancel-in-progress: false

jobs:
${BUILD_JOB}

${indent(deployJob, 4)}
`
}

async function readIfExists(file) {
    try {
        return await fs.readFile(file, 'utf-8')
    } catch (err) {
        if (err.code === 'ENOENT') return null
        throw err
    }
}

// Write the workflow for `adapter` into the site at `cwd`. Returns
// `{ file, status, message }`: status `created`, `updated` or `unchanged`, or
// `kept` when the file exists without GENERATED_HEADER and is left alone;
// `message` says what happened, for the user.
export async function writeWorkflow(adapter, ctx = {}, cwd = process.cwd()) {
    const file = path.join(cwd, WORKFLOW_FILE)
    const existing = await readIfExists(file)
    if (existing !== null && !existing.startsWith(GENERATED_HEADER)) {
        return {
            file,
            status: 'kept',
            message: `Kept your ${WORKFLOW_FILE}: it no longer starts with the line \`nera publish\` writes. Make sure it builds the site and deploys it to ${adapter.label}.`,
        }
    }

    const text = await renderWorkflow(adapter, ctx)
    if (existing === text) {
        return { file, status: 'unchanged', message: `${WORKFLOW_FILE} is up to date.` }
    }
    await fs.mkdir(path.dirname(file), { recursive: true })
    await fs.writeFile(file, text)
    return existing === null
        ? { file, status: 'created', message: `Created ${WORKFLOW_FILE}.` }
        : { file, status: 'updated', message: `Updated ${WORKFLOW_FILE}.` }
}
